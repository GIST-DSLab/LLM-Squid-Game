def table(key, title, fields, rows, src="evidence"):
    # These are authored review matrices, not SQL result tables. Keep them
    # as semantic Markdown rather than invent SQL provenance for prose.
    lines = ["| " + " | ".join(label for _,label in fields) + " |",
             "| " + " | ".join("---" for _ in fields) + " |"]
    for row in rows:
        lines.append("| " + " | ".join(str(row[f]).replace("|", " / ") for f,_ in fields) + " |")
    md(key, title, "\n".join(lines), src if src == "evidence" else None)


