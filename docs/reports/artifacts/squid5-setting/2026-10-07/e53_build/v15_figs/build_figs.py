SHAPE_NAME = {1.0: "100%", 0.75: "75%", 0.5: "50%", 0.25: "25%"}


def shape(share, x, y, r, style, cls, tip):
    if share == 1.0:
        g = f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r}"'
    elif share == 0.75:
        g = f'<rect x="{x - r * .9:.1f}" y="{y - r * .9:.1f}" width="{r * 1.8:.1f}" height="{r * 1.8:.1f}"'
    elif share == 0.5:
        g = f'<path d="M{x:.1f},{y - r * 1.25:.1f}L{x + r * 1.25:.1f},{y:.1f}L{x:.1f},{y + r * 1.25:.1f}L{x - r * 1.25:.1f},{y:.1f}z"'
    else:
        g = f'<path d="M{x:.1f},{y - r * 1.25:.1f}L{x + r * 1.15:.1f},{y + r * .85:.1f}L{x - r * 1.15:.1f},{y + r * .85:.1f}z"'
    return f'{g} class="{cls}" style="{style}"><title>{tip}</title>' + ("</circle>" if share == 1.0 else "</rect>" if share == 0.75 else "</path>")


def exit_rows(d):
    """One row per seat per game: EXIT (round, balance just before leaving) or, if it never exited, its lowest point."""
    rows = []
    for m, md in d["models"].items():
        for gi, g in enumerate(md["games"]):
            mk = {x["seat"]: x for x in g["marks"]}
            for s in SEATS:
                share = g["starts"][s] / START
                if s in mk and mk[s]["kind"] == "exit":
                    rows.append({"m": m, "game": gi + 1, "seat": s, "share": share, "kind": "exit", "r": mk[s]["r"],
                                 "y": round(mk[s]["bal"] / START * 100, 1)})
                    continue
                lo, lr = None, 1
                for stp in g["steps"]:
                    if s in stp["b"] and (lo is None or stp["b"][s] < lo):
                        lo, lr = stp["b"][s], stp["r"]
                rows.append({"m": m, "game": gi + 1, "seat": s, "share": share,
                             "kind": "zero" if lo <= 0 else "low", "r": lr, "y": round(max(lo, 0) / START * 100, 1)})
    return rows


