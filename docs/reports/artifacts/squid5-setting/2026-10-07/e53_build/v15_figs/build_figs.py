def shares(r, n, rng):
    """Engine shares p for this round (consistent-rule shares), top action at random."""
    top = min(0.97, max(0.35, 0.95 - 0.30 * (r - 1) / (ROUNDS - 1) - 0.07 * (4 - n)))
    w = [rng.random() + 0.05 for _ in range(3)]
    rest = [(1 - top) * x / sum(w) for x in w]
    acts = ACTIONS[:]; rng.shuffle(acts)
    return dict(zip(acts, [top] + rest))


def draw(p, rng):
    u, acc = rng.random(), 0.0
    for a, v in p.items():
        acc += v
        if u < acc:
            return a
    return a


def simulate(st, rot, rng, skill):
    """One toy game. Returns steps (balance snapshot after each step) and seat events."""
    starts = {s: int(START * SHARES[(i + rot) % 4]) for i, s in enumerate(SEATS)}
    bal = dict(starts)
    status = {s: "in" for s in SEATS}
    steps = [{"r": 1, "k": "start", "b": dict(bal)}]
    marks, gifts, solves, coop = [], [], [], []
    acct = {s: {"talk": 0, "U": 0.0, "I": 0.0, "luck": 0.0, "recv": 0, "given": 0, "solves": 0} for s in SEATS}

    def step(r, k, **kw):
        steps.append({"r": r, "k": k, "b": {s: bal[s] for s in SEATS if status[s] == "in" or kw.get("seat") == s}, **kw})

    for r in range(1, ROUNDS + 1):
        live = [s for s in SEATS if status[s] == "in"]
        if not live:
            break
        x0 = {s: bal[s] / START * 100 for s in live}  # balance % at the round's start
        rec = {s: {"r": r, "seat": s, "x": round(x0[s], 1), "ask": 0, "gave": 0, "to_x": None, "asked": 0,
                   "given_to_askers": 0} for s in live}
        top_gift = {}
        for s in live:  # TALK: tokens spent, never returned
            c = min(bal[s], max(40, int(rng.gauss(st["talk"], st["talk"] * 0.35))))
            bal[s] -= c
            acct[s]["talk"] += c
            step(r, "talk", seat=s, d=-c)
            if bal[s] <= 0:
                status[s] = "zero"; marks.append({"seat": s, "r": r, "kind": "zero", "i": len(steps) - 1})
            elif st["exit_below"] and bal[s] < st["exit_below"] * START:
                status[s] = "exit"; marks.append({"seat": s, "r": r, "kind": "exit", "i": len(steps) - 1,
                                                  "bal": bal[s]})
                step(r, "exit", seat=s, d=0)
        live = [s for s in SEATS if status[s] == "in"]

        def give(src, dst, g, how):
            bal[src] -= g; bal[dst] += g
            acct[src]["given"] += g; acct[dst]["recv"] += g
            gifts.append({"r": r, "src": src, "dst": dst, "n": g, "how": how})
            step(r, "gift", seat=src, dst=dst, d=g)
            rec[src]["gave"] += g
            if g > top_gift.get(src, 0):
                top_gift[src] = g; rec[src]["to_x"] = round(x0[dst], 1)

        for s in [a for a in live if len(live) >= 2]:  # ASK -> the richest other seat; its DECISION
            if rng.random() < min(0.95, max(0.0, st["ask0"] + st["ask1"] * (1 - min(x0[s], 100) / 100) ** 2)):
                dst = max((a for a in live if a != s), key=lambda a: bal[a])
                n = rng.randint(st["ask_lo"], st["ask_hi"]) * START // 100
                rec[s]["ask"] += n; rec[dst]["asked"] += n
                yes = st["yes_rich"] if bal[dst] > 0.40 * START else st["yes_poor"]
                if rng.random() < yes:
                    ratio = rng.choice([0.5, 1.0, 1.0, 1.0, 1.5]) if bal[dst] > 0.40 * START else 0.5
                    g = min(bal[dst] - 1, int(n * ratio) // 100 * 100)
                    if g > 0:
                        give(dst, s, g, "ask")
                        rec[dst]["given_to_askers"] += g
        poor = sorted(live, key=lambda s: bal[s])
        if len(live) >= 2 and bal[poor[0]] < st["give_when"] * START:  # unasked GIVE: richest -> poorest
            rich = poor[-1]
            if bal[rich] > 0.40 * START and rng.random() < st["give_p"]:
                give(rich, poor[0], min(bal[rich] - 1, rng.randint(st["give_lo"], st["give_hi"]) // 100 * 100), "open")
        coop.extend(rec.values())
        n = len(live)
        p = shares(r, n, rng)
        truth = draw(p, rng)
        top = max(p, key=p.get)
        cost = {}
        for s in live:  # SOLVE call
            x = bal[s] / START * 100
            c = max(300, int(rng.gauss(st["solve"], st["solve"] * 0.3)))
            void = c >= bal[s]
            c = min(c, bal[s])
            if void:
                a = None
            elif rng.random() < skill:
                a = top
            else:
                others = {k: v for k, v in p.items() if k != top}
                a = draw({k: v / sum(others.values()) for k, v in others.items()}, rng)
            ok = a == truth
            kl = math.exp(rng.gauss(math.log(st["kl_base"]) + st["kl_slope"] * (1 - min(x, 100) / 100), 0.45))
            solves.append({"r": r, "seat": s, "x": round(x, 1), "kl": None if void else round(kl, 4), "ok": ok,
                           "pmax": round(p[top], 4), "pa": round(p.get(a, 0.0), 4)})
            cost[s] = (c, ok, p.get(a, 0.0))
            bal[s] -= c
            step(r, "solve", seat=s, d=-c)
        for s in live:  # settlement
            c, ok, pa = cost[s]
            w = c + min(CHARGE, bal[s])  # what a wrong answer actually costs (charge capped at the balance)
            loss = 0 if ok else w
            U, I, luck = w * (1 - p[top]), w * (p[top] - pa), loss - w * (1 - pa)
            assert abs(U + I + luck - loss) < 1e-6
            acct[s]["U"] += U; acct[s]["I"] += I; acct[s]["luck"] += luck; acct[s]["solves"] += 1
            delta = c if ok else -min(CHARGE, bal[s])
            bal[s] += delta
            step(r, "settle", seat=s, d=delta)
            if bal[s] <= 0:
                status[s] = "zero"; marks.append({"seat": s, "r": r, "kind": "zero", "i": len(steps) - 1})
    for s in SEATS:  # waterfall identity: start - talk - U - I - luck + recv - given = end
        a = acct[s]
        assert abs(starts[s] - a["talk"] - a["U"] - a["I"] - a["luck"] + a["recv"] - a["given"] - bal[s]) < 1e-6
        a["end"] = bal[s]
        for k in ("U", "I", "luck"):
            a[k] = round(a[k], 3)
    return {"starts": starts, "steps": steps, "marks": marks, "gifts": gifts, "solves": solves, "coop": coop, "acct": acct,
            "final": {s: (bal[s] if status[s] == "in" else status[s]) for s in SEATS}}


def wanted(m, gi, g):
    low = min(g["starts"], key=g["starts"].get)
    if m == "A":
        return sum(1 for x in g["gifts"] if x["dst"] == low) >= 2 and not any(x["seat"] == low for x in g["marks"])
    if m == "B":
        return any(x["kind"] == "zero" for x in g["marks"]) if gi == 0 else len(g["marks"]) <= 1
    return sum(1 for x in g["marks"] if x["kind"] == "exit") >= (2 if gi == 0 else 1)


def wanted_any(m, gi, g):
    return wanted(m, gi, g) if gi < GAMES_PER_MODEL else True  # graph-5-only games: first seed, no selection


def build_data():
    out = {"note": "SYNTHETIC toy data (expected v15 result), not a measurement. See build_figs.py docstring.",
           "seed": SEED, "models": {}}
    for mi, (m, st) in enumerate(STYLES.items()):
        games = []
        for gi in range(GAMES_G5):
            for tries in range(500):  # first seed whose game shows the illustrated event
                g = simulate(st, ROT[gi], random.Random(SEED * 1000 + mi * 100 + gi * 10 + tries * 7919), SKILL[m])
                if wanted_any(m, gi, g):
                    break
            g["tries"] = tries
            games.append(g)
        out["models"][m] = {"name": st["name"], "tag": st["tag"], "games": games[:GAMES_PER_MODEL],
                            "extra": games[GAMES_PER_MODEL:]}
    return out


def spearman(xs, ys):
    def rank(v):
        o = sorted(range(len(v)), key=lambda i: v[i]); r = [0.0] * len(v); i = 0
        while i < len(o):
            j = i
            while j + 1 < len(o) and v[o[j + 1]] == v[o[i]]:
                j += 1
            for k in range(i, j + 1):
                r[o[k]] = (i + j) / 2
            i = j + 1
        return r
    a, b = rank(xs), rank(ys); ma, mb = sum(a) / len(a), sum(b) / len(b)
    num = sum((p - ma) * (q - mb) for p, q in zip(a, b))
    den = math.sqrt(sum((p - ma) ** 2 for p in a) * sum((q - mb) ** 2 for q in b))
    return num / den


def median(v):
    v = sorted(v); n = len(v)
    return v[n // 2] if n % 2 else (v[n // 2 - 1] + v[n // 2]) / 2


