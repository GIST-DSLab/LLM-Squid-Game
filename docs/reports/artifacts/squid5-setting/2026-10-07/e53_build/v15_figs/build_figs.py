def exit_rows(d):
    """One row per seat per game: EXIT (round, balance just before leaving) or, if it never exited, its lowest point."""
    rows = []
    for m, md in d["models"].items():
        for gi, g in enumerate(md["games"]):
            mk = {x["seat"]: x for x in g["marks"]}
            for s in SEATS:
                share = g["starts"][s] / START
                if s in mk and mk[s]["kind"] == "exit":
                    rows.append({"m": m, "game": gi + 1, "seat": s, "share": share, "kind": "exit", "r": mk[s]["r"],
                                 "y": round(mk[s]["bal"] / START * 100, 1)})
                    continue
                lo, lr = None, 1
                for stp in g["steps"]:
                    if s in stp["b"] and (lo is None or stp["b"][s] < lo):
                        lo, lr = stp["b"][s], stp["r"]
                rows.append({"m": m, "game": gi + 1, "seat": s, "share": share,
                             "kind": "zero" if lo <= 0 else "low", "r": lr, "y": round(max(lo, 0) / START * 100, 1)})
    return rows


