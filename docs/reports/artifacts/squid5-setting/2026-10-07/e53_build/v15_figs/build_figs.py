def wf_steps(a):
    """Running total for the waterfall: list of (key, label, from, to)."""
    run, out = 5000.0, [("start", "시작", 0.0, 5000.0)]
    for k, lab in WF_ROWS[1:-1]:
        dv = a[k] if k == "recv" else -a[k]
        out.append((k, lab, run, run + dv)); run += dv
    out.append(("end", "끝 토큰", 0.0, run))
    assert abs(run - a["end"]) < 0.01
    return out


