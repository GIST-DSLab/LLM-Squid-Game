def panel_balance(g, ymax, title):
    W, H, L, R, T, B = 320, 188, 34, 10, 8, 22
    n = len(g["steps"]) - 1
    X = lambda i: L + (W - L - R) * i / n
    Y = lambda v: T + (H - T - B) * (1 - v / ymax)
    o = [f'<svg viewBox="0 0 {W} {H}" role="img" aria-label="{title}: 네 자리 잔액 (가상 데이터)">']
    for v in range(0, ymax + 1, 10000):
        o.append(f'<line class="v15f-grid" x1="{L}" x2="{W - R}" y1="{Y(v):.1f}" y2="{Y(v):.1f}"/>'
                 f'<text class="v15f-tick" x="{L - 4}" y="{Y(v) + 3:.1f}" text-anchor="end">{v // 1000}k</text>')
    first = {}
    for i, s in enumerate(g["steps"]):
        first.setdefault(s["r"], i)
    last = -99
    for r, i in first.items():
        o.append(f'<line class="v15f-rline" x1="{X(i):.1f}" x2="{X(i):.1f}" y1="{T}" y2="{H - B}"/>')
        if (r % 2 == 1 or r == 12) and X(i) - last >= 20 and X(i) < W - R - 16:
            o.append(f'<text class="v15f-tick" x="{X(i) + 1.5:.1f}" y="{H - B + 11}">R{r}</text>')
            last = X(i)
    o.append(f'<text class="v15f-tick" x="{W - R}" y="{H - 1}" text-anchor="end">차례 →</text>')
    for s in SEATS:
        pts, prev = [], None
        for i, st in enumerate(g["steps"]):
            if s not in st["b"]:
                continue
            v = st["b"][s]
            if prev is not None:
                pts.append(f"{X(i):.1f},{Y(prev):.1f}")
            pts.append(f"{X(i):.1f},{Y(v):.1f}")
            prev = v
        o.append(f'<polyline class="v15f-ln" style="stroke:var({SEAT_VAR[s]})" points="{" ".join(pts)}">'
                 f'<title>{s} (시작 {fmt(g["starts"][s])})</title></polyline>')
    for i, stp in enumerate(g["steps"]):
        if stp["k"] == "gift":
            x, y = X(i), Y(stp["b"][stp["dst"]])
            o.append(f'<path class="v15f-tri" d="M{x:.1f},{y - 6:.1f}l3.6,6h-7.2z" style="fill:var({SEAT_VAR[stp["dst"]]})">'
                     f'<title>{stp["dst"]}가 {stp["seat"]}에게서 GIVE {fmt(stp["d"])} 토큰, R{stp["r"]}</title></path>')
    for mk in g["marks"]:
        x, y = X(mk["i"]), Y(g["steps"][mk["i"]]["b"].get(mk["seat"], 0))
        c = SEAT_VAR[mk["seat"]]
        if mk["kind"] == "exit":
            o.append(f'<rect class="v15f-ring" x="{x - 4:.1f}" y="{y - 4:.1f}" width="8" height="8" '
                     f'style="stroke:var({c})"><title>{mk["seat"]} EXIT, R{mk["r"]}, {fmt(mk["bal"])} 토큰</title></rect>')
