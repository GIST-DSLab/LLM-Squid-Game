BINS = [0, 20, 40, 60, 80, 100, 1e9]


def recip_fill(x):
    return next(c for lim, c, _ in RECIP if x < lim)


def binned(recs, key):
    out = []
    for lo, hi in zip(BINS, BINS[1:]):
        v = [r for r in recs if lo <= r["x"] < hi]
        if len(v) >= 3:
            out.append(((lo + min(hi, 125)) / 2 if hi < 1e9 else 110, sum(r[key] for r in v) / len(v) / START * 100,
                        sum(1 for r in v if r[key] > 0) / len(v), len(v)))
    return out


def panel_coop(m, recs, key, xmax, ymax, jit):
    """4a (key='ask') / 4b (key='gave'): one point per seat-round; binned mean + share with any (right axis)."""
    W, H, L, R, T, B = 300, 200, 32, 34, 10, 30
    X = lambda v: L + (W - L - R) * min(v, xmax) / xmax
    Y = lambda v: T + (H - T - B) * (1 - v / ymax)
    Ys = lambda f: T + (H - T - B) * (1 - f)
    st = STYLES[m]
    lab = "요청" if key == "ask" else "증여"
    o = [f'<svg viewBox="0 0 {W} {H}" role="img" aria-label="{st["name"]} {lab}: 남은 토큰 % 대 {lab} 토큰 % (가상 데이터)">']
    for yv in range(0, int(ymax) + 1, 5):
        o.append(f'<line class="v15f-grid" x1="{L}" x2="{W - R}" y1="{Y(yv):.1f}" y2="{Y(yv):.1f}"/>'
                 f'<text class="v15f-tick" x="{L - 4}" y="{Y(yv) + 3:.1f}" text-anchor="end">{yv}%</text>')
    for f in (0, 0.5, 1):
        o.append(f'<text class="v15f-tick v15f-share-t" x="{W - R + 4}" y="{Ys(f) + 3:.1f}">{int(f * 100)}%</text>')
    for xv in range(0, xmax + 1, 25):
        o.append(f'<text class="v15f-tick" x="{X(xv):.1f}" y="{H - B + 12}" text-anchor="middle">{xv}%</text>')
    o.append(f'<text class="v15f-tick" x="{(L + W - R) / 2:.1f}" y="{H - 3}" text-anchor="middle">라운드 시작 때 남은 토큰 (20,000 대비)</text>')
    for r in recs:
        v = r[key] / START * 100
        tip = f'{r["seat"]} R{r["r"]}: 남은 {r["x"]}%, {lab} {fmt(r[key])} 토큰'
        if v == 0:
            o.append(f'<circle class="v15f-zero" cx="{X(r["x"]):.1f}" cy="{Y(0) - jit.uniform(0.5, 5):.1f}" r="2"><title>{tip}</title></circle>')
