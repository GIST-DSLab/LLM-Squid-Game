def main():
    d = build_data()
    html = build_html(d)
    slim = json.loads(json.dumps(d))
    for md in slim["models"].values():
        for g in md["games"]:
            g["seats"] = SEATS
            for st in g["steps"]:
                st["b"] = [st["b"].get(s) for s in SEATS]
    DATA.write_text(json.dumps(slim, ensure_ascii=False, separators=(",", ":")))
    h = PAGE.read_text()  # read fresh right before writing
    if MARK_S in h:
        a = h.index(MARK_S)
        b = h.index(MARK_E, a) + len(MARK_E)
        h = h[:a] + html + h[b:]
    else:
        i = h.index(AFTER) + len(AFTER)
        h = h[:i] + "\n" + html + h[i:]
    PAGE.write_text(h)
    for m, md in d["models"].items():
        for gi, g in enumerate(md["games"]):
            print(m, gi + 1, "steps", len(g["steps"]) - 1, "tries", g["tries"], "marks",
                  [(x["seat"], x["kind"], x["r"]) for x in g["marks"]], "gifts", len(g["gifts"]), "final", g["final"])
    print("kl", d["kl_stats"])


if __name__ == "__main__":
    main()
