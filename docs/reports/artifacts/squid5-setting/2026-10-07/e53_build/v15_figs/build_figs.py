def panel_kl(m, pts, fits, xmax, ymax):
    W, H, L, R, T, B = 240, 200, 30, 16, 8, 30
    X = lambda v: L + (W - L - R) * v / xmax
    Y = lambda v: T + (H - T - B) * (1 - min(v, ymax) / ymax)
    st = STYLES[m]
    o = [f'<svg viewBox="0 0 {W} {H}" role="img" aria-label="{st["name"]}: 남은 토큰 % 대 KL (가상 데이터)">']
    yt = 0.0
    while yt <= ymax + 1e-9:
        o.append(f'<line class="v15f-grid" x1="{L}" x2="{W - R}" y1="{Y(yt):.1f}" y2="{Y(yt):.1f}"/>'
                 f'<text class="v15f-tick" x="{L - 4}" y="{Y(yt) + 3:.1f}" text-anchor="end">{yt:.1f}</text>')
        yt += 0.5
    for xv in range(0, xmax + 1, 25):
        o.append(f'<text class="v15f-tick" x="{X(xv):.1f}" y="{H - B + 12}" text-anchor="middle">{xv}%</text>')
    o.append(f'<text class="v15f-tick" x="{(L + W - R) / 2:.1f}" y="{H - 3}" text-anchor="middle">남은 토큰 (20,000 대비)</text>')
    for k, (a, b, lo, hi) in fits.items():
        if k != m:
            o.append(f'<line class="v15f-ghost" x1="{X(lo):.1f}" y1="{Y(a + b * lo):.1f}" x2="{X(hi):.1f}" y2="{Y(a + b * hi):.1f}"/>')
    for p in pts:
        o.append(f'<circle class="v15f-pt" cx="{X(min(p["x"], xmax)):.1f}" cy="{Y(p["kl"]):.1f}" r="2.4" '
                 f'style="fill:var({st["var"]})"><title>{p["seat"]} R{p["r"]}: {p["x"]}%, KL {p["kl"]:.3f}</title></circle>')
    a, b, lo, hi = fits[m]
    o.append(f'<line class="v15f-fit" x1="{X(lo):.1f}" y1="{Y(a + b * lo):.1f}" x2="{X(hi):.1f}" y2="{Y(a + b * hi):.1f}" '
             f'style="stroke:var({st["var"]})"/>')
    o.append("</svg>")
    return "".join(o)


