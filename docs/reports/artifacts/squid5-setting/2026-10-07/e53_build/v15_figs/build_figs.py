def seat_path(g, s):
    """Per round end: balance and ledger (balance - received + given) of seat s; plus how it left."""
    recv = given = 0
    bal_r, led_r, led_min_r = {0: g["starts"][s]}, {0: g["starts"][s]}, None
    for stp in g["steps"][1:]:
        if stp["k"] == "gift":
            if stp["dst"] == s:
                recv += stp["d"]
            if stp["seat"] == s:
                given += stp["d"]
        if s not in stp["b"]:
            continue
        b = stp["b"][s]
        bal_r[stp["r"]], led_r[stp["r"]] = b, b - recv + given
        if led_min_r is None and b - recv + given <= 0:
            led_min_r = stp["r"]
    mk = next((x for x in g["marks"] if x["seat"] == s), None)
    return {"bal": bal_r, "led": led_r, "led_zero": led_min_r, "end_kind": mk["kind"] if mk else "in",
            "end_r": mk["r"] if mk else ROUNDS}


def km(items):
    """items: (time, event). Event at round r; censored times sit between rounds. Returns S at r = 0..12 and censor marks."""
    S, out, cens = 1.0, [1.0], []
    for r in range(1, ROUNDS + 1):
        at_risk = sum(1 for t, e in items if t >= r)
        d = sum(1 for t, e in items if e and t == r)
        if at_risk:
            S *= 1 - d / at_risk
        out.append(S)
        cens += [(t, S) for t, e in items if not e and r - 1 < t <= r]
    return out, cens


def km_items(paths, ledger=False):
    it = []
    for pth in paths:
        if ledger and pth["led_zero"] is not None:
            it.append((pth["led_zero"], True))
        elif pth["end_kind"] == "zero" and not ledger:
            it.append((pth["end_r"], True))
        elif pth["end_kind"] == "exit":
            it.append((pth["end_r"] - 0.5, False))
        elif pth["end_kind"] == "zero":
            it.append((pth["end_r"] + 0.25, False))
        else:
            it.append((ROUNDS + 0.5, False))
    return it


def g5_data(d):
    out = {}
    for m, md in d["models"].items():
        gs = md["games"] + md["extra"]
        by = {sh: [] for sh in SHARES}
        accts = []
        for g in gs:
            for s in SEATS:
                sh = g["starts"][s] / START
                by[sh].append(seat_path(g, s))
                if sh == 0.25:
                    accts.append(g["acct"][s])
        keys = ("talk", "U", "I", "luck", "recv", "given", "end", "solves")
        avg = {k: sum(a[k] for a in accts) / len(accts) for k in keys}
        assert abs(5000 - avg["talk"] - avg["U"] - avg["I"] - avg["luck"] + avg["recv"] - avg["given"] - avg["end"]) < 0.01  # U/I/luck stored to 3 decimals
        out[m] = {"paths": by, "acct_avg": avg, "n25": len(accts)}
    return out


