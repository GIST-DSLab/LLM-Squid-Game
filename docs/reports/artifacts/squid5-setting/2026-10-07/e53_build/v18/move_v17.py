gini = old["e52-v17gini"].replace("e52-v17gini", "e52-v18gini").replace('href="#e52-v18gini-real"', 'href="#e52-v18real-g5"')
gini = gini.replace("실측 다섯 판은 <a", "v17b 첫 실측(시드 4100)은 <a href=\"e52-legacy.html#e52-v17gini-real\">지난 설계</a>에, v18 실측은 오른쪽 <a").replace(">v17b 첫 실측</a>에 있습니다", ">칸</a>에 둡니다")
