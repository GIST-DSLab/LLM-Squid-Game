# --- TOC on every page, site.js ------------------------------------------------------------------------------------
for p in sorted(D.glob("*.html")):
    t = p.read_text(encoding="utf-8")
    if "e52-v17real-toc" not in t:
        continue
    cur = "#" if p.name == "e52.html" else "e52.html#"
    leg = "#" if p.name == "e52-legacy.html" else "e52-legacy.html#"
    old_toc = "".join(re.search(rf'  <li><a href="[^"]*e52-v17{x}">[^\n]*<!-- e52-v17{x}-toc -->\n', t).group(0) for x in ("real", "round", "metrics", "figs"))
    assert old_toc in t, p
    t = t.replace(old_toc, f'  <li><a href="{cur}e52-v18real">v18 실측 · 다섯 모델 × 3판</a></li><!-- e52-v18real-toc -->\n'
                           f'  <li><a href="{cur}e52-v18round">v18 · 한 라운드 (현재 구현)</a></li><!-- e52-v18round-toc -->\n'
                           f'  <li><a href="{cur}e52-v18metrics">v18 · 측정 지표 (네 축)</a></li><!-- e52-v18metrics-toc -->\n'
                           f'  <li><a href="{cur}e52-v18figs">v18 · 예상 그래프 · 실측 나란히</a></li><!-- e52-v18figs-toc -->\n', 1)
    t = t.replace('<span class="xid">5.2</span>행동 · 현재 (v17)</a>', '<span class="xid">5.2</span>행동 · 현재 (v18)</a>', 1)
    m = re.search(r'(<li><a href="[^"]*e52-legacy"><span class="xid">5\.2</span>지난 설계 · )v0~v16(</a>\n  <ol>\n)', t)
    assert m, p
    t = t[:m.start()] + m.group(1) + "v0~v17" + m.group(2) + (
        f'  <li><a href="{leg}e52-v17real">v17b 첫 실측 · 다섯 모델 (10-15)</a></li><!-- e52-v17real-toc -->\n'
        f'  <li><a href="{leg}e52-v17round">v17 · 한 라운드 (순번제, 10-15)</a></li><!-- e52-v17round-toc -->\n'
        f'  <li><a href="{leg}e52-v17metrics">v17 · 측정 지표</a></li><!-- e52-v17metrics-toc -->\n') + t[m.end():]
    for x in ("real", "round", "metrics", "gini-real"):
        t = t.replace(f'href="e52.html#e52-v17{x}"', f'href="{leg}e52-v17{x}"')
    for x in ("figs", "switch"):
        t = t.replace(f'href="e52.html#e52-v17{x}"', f'href="{cur}e52-v18{x}"')
    p.write_text(t, encoding="utf-8")

