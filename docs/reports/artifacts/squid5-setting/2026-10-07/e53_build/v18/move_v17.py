figs = figs.replace('<h3 id="e52-v18figs">v17 · 스피노자 → 홉스 전환 · 예상 결과 그래프 (가상 데이터)</h3>',
                    '<h3 id="e52-v18figs">v18 · 예상 그래프와 실측 나란히 (예상은 가상 데이터)</h3>')
