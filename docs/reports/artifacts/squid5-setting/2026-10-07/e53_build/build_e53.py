"""Build e53.html (5.3 signal game, current: v15) and e53-legacy.html (5.3 past designs, v12 ~ M6) from
e53_template.html + s4000.json, and wire both into the other pages (TOC, links, site.js).

Usage: python3 build_e53.py <dir with template + s4000.json> <report dir>. Idempotent.
The template stays one file so the block builders (m6_grid, v15_grid, verify_v14f) keep their markers. The split:
e53.html = a short intro + the CURRENT blocks (CUR_BLOCKS marker ranges); e53-legacy.html = the rest of the
template byte-for-byte (old h2 becomes #e53-legacy) incl. the s4000 widget and its script. Cross-page #links are
rewritten between the two pages and on every other page (e53.html#moved -> e53-legacy.html#moved).
s4000.json comes from gen.py (run in ~/wt/squid5-e52: PYTHONPATH=. python gen.py 4000); each round also carries
"held", the same round dealt with all_held (no public example).
"""
import json, re, sys, pathlib
sp, d = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
src = json.load(open(sp / "s4000.json"))
rounds = []
for r in src["rounds"]:  # the 10-06 smoke ran the old condition space (>=, <=, % 2), so its results are not shown here
    h = r["held"]  # the same round dealt with all_held (no public example)
    sm = f"{sum(len(v) for v in h['secret'].values())}장"
    rounds.append({"r": r["round"], "prof": r["profile"], "shape": r["shape"], "cl": r["clauses"], "el": r["else"],
                   "pub": r["public"], "sec": {a: v[0] for a, v in r["secret"].items()}, "need": r["needed"],
                   "open": r["open"], "wh": r["withheld"][0] if r["withheld"] else None, "q": r["queries"][0],
                   "ans": r["answers"][0], "cp": r["cands_public_only"][0], "ca": r["cands_all"][0],
                   "co": {a: v[0] for a, v in r["cands_own"].items()}, "trap": "t" in r["profile"][2:],
                   "view": r["view"], "smoke": sm,
                   "H": {"pub": [], "sec": h["secret"], "need": h["needed"], "open": h["open"],
                         "wh": h["withheld"][0] if h["withheld"] else None, "ca": h["cands_all"][0],
                         "co": {a: v[0] for a, v in h["cands_own"].items()},
                         "lose": {a: v[0] for a, v in h["cands_lose"].items()}, "view": h["view"], "subs": h["subs"]},
                   "subs": r["subs"]})
seats = {"agent-6": {"model": "Fable 5.1", "c": "--s-fable"}, "agent-11": {"model": "Opus 5.5", "c": "--s-opus"},
         "agent-17": {"model": "GPT-6 Astra", "c": "--s-astra"}, "agent-23": {"model": "GPT-6 Luna", "c": "--s-gpt"}}
data = json.dumps({"agents": src["agents"], "seats": seats, "rounds": rounds}, ensure_ascii=False, separators=(",", ":"))
sec = (sp / "e53_template.html").read_text().replace("__DATA__", data.replace("</", "<\\/"))

# ---- split the template: current (v15) blocks -> e53.html, everything else -> e53-legacy.html ----
CUR_BLOCKS = ["e53-v15grid"]  # marker names <!-- NAME:start ... --> ... <!-- NAME:end -->; add a block here to promote it
cur_parts, leg = [], sec
for b in CUR_BLOCKS:
    i, j = leg.index(f"<!-- {b}:start"), leg.index(f"<!-- {b}:end -->") + len(f"<!-- {b}:end -->")
    cur_parts.append(leg[i:j])
    if leg[j:j + 2] == "\n\n":
        j += 2
    leg = leg[:i] + leg[j:]
cur_body = "\n\n".join(cur_parts)
OLD_H2 = '<section aria-labelledby="e53" class="sg53">\n<h2 id="e53"><span class="xid">5.3</span>시그널 게임 — 라운드마다 푸는 과제</h2>\n'
assert OLD_H2 in leg, "template h2 changed"
leg = leg.replace(OLD_H2,
    '<!-- ============ 5.3 legacy (v12 ~ M6) ============ -->\n'
    '<section aria-labelledby="e53-legacy" class="sg53">\n'
    '<h2 id="e53-legacy"><span class="xid">5.3</span>지난 설계 — v12 ~ M6</h2>\n'
    '<div class="callout warn"><span class="lbl">기록 보관 · 현재 세팅에 쓰지 않음</span><p>v15 이전 설계 — v12 ~ M6. '
    '한 라운드 그림(seed 4000), 문제 생성 · 유일성, 가설 공간, v13 손패 사다리, v14 비율 · v14f 정답률 검증, M6 표, '
    'v12 힌트 배분 · 채점을 10-13에 옮긴 그대로 둡니다. 지금의 난이도 통제(v15 엔트로피 사다리)는 '
    '<a href="e53.html#e53-v15grid">5.3 시그널 게임 · 현재</a>에 있습니다. 바로 아래 문단은 v12~v14 때의 5.3 소개입니다.</p></div>\n', 1)
k = sec.index("\n</section>\n\n<style>") + len("\n</section>\n\n")
tail = re.sub(r'<script type="application/json" id="sg53-data">.*?</script>\n<script>.*?</script>\n', "",
              sec[k:], count=1, flags=re.S)  # styles only: the s4000 widget lives on the legacy page
cur = ('<!-- e53:start (signal game, current v15; generated by build_e53.py, past designs in e53-legacy.html) -->\n'
       '<section aria-labelledby="e53" class="sg53">\n'
       '<h2 id="e53"><span class="xid">5.3</span>시그널 게임 — 라운드마다 푸는 과제 (v15)</h2>\n'
       '<p class="lede">시그널 게임은 5.2 아레나의 매 라운드 과제입니다. 숨은 <code>if / elif / else</code> 규칙 하나가 '
       '신호 64개(색 4 × 모양 4 × 숫자 1–4)를 행동 넷 중 하나로 보내고, 모델은 공개된 예시를 보고 질문한 신호의 행동을 답합니다. '
       '지금의 난이도 통제는 아래 <b>v15 엔트로피 사다리</b>입니다: 라운드와 남은 인원마다 네 행동 분포의 엔트로피 범위를 정해 문제를 고릅니다. '
       'v12 ~ M6의 지난 설계(한 라운드 그림, 유일성 보장, 가설 공간, v14 비율, M6 표 등)는 '
       '<a href="e53-legacy.html#e53-legacy">5.3 지난 설계</a>에 있습니다.</p>\n\n'
       + cur_body + '\n</section>\n\n' + tail)

ID = re.compile(r'\bid="([^"]+)"')
cur_ids, leg_ids = set(ID.findall(cur)), set(ID.findall(leg))
assert not cur_ids & leg_ids, cur_ids & leg_ids

def fix_links(h, here, other_page, other_ids):
    """#id -> other_page#id for ids on the other page; here.html#id -> #id for ids on this page."""
    h = re.sub(r'href="#([^"]+)"', lambda m: f'href="{other_page}#{m.group(1)}"' if m.group(1) in other_ids else m.group(0), h)
    return re.sub(rf'href="{re.escape(here)}#([^"]+)"', lambda m: f'href="#{m.group(1)}"' if m.group(1) not in other_ids else m.group(0), h)

cur = fix_links(cur, "e53.html", "e53-legacy.html", leg_ids)
leg = fix_links(leg, "e53-legacy.html", "e53.html", cur_ids)

CUR_TOC = [("e53-v15grid", "엔트로피 사다리 · 라운드 × 인원 표 (v15)"), ("e53-davinci", "불확실 = 어려움 · 다빈치 코드 비유")]
LEG_TOC = [("e53-fig", "한 라운드 · 규칙 · 비밀 예시 (그림)"), ("e53-ramp", "난이도 · 12라운드 사다리"),
           ("e53-ops", "조건 · 연산자는 == 하나"), ("e53-unique", "문제 생성 · 유일성 보장"),
           ("e53-space", "가설 공간 · 규칙은 몇 개인가"), ("e53-dealn", "힌트 배분 · 최대 10명 (v13)"),
           ("e53-difficulty", "난이도 통제 · 손패 사다리 점검 (v13)"), ("e53-v14diff", "난이도 · v14 정의 · 답 사이 비율"),
           ("e53-v14split", "v14 비율 일정 · 실현 가능성"), ("e53-v14verify", "검증 · 실제 정답률 (v14f)"),
           ("e53-m6grid", "미리 만든 판 · 라운드 × 인원 표 (M6)"), ("e53-deal", "힌트 배분 (v12)"), ("e53-score", "채점 · 행동만")]
assert {i for i, _ in CUR_TOC} <= cur_ids and {i for i, _ in LEG_TOC} <= leg_ids
TOC = ('<li><a href="{c}e53"><span class="xid">5.3</span>시그널 게임 · 과제 (v15)</a>\n  <ol>\n'
       + "".join(f'  <li><a href="{{c}}{i}">{t}</a></li>\n' for i, t in CUR_TOC) + '  </ol></li>\n'
       '<li><a href="{l}e53-legacy"><span class="xid">5.3</span>지난 설계 · v12 ~ M6</a>\n  <ol>\n'
       + "".join(f'  <li><a href="{{l}}{i}">{t}</a></li>\n' for i, t in LEG_TOC) + '  </ol></li><!-- e53-toc -->\n')
OLD_TOC = re.compile(r'<li><a href="[^"]*e53"><span class="xid">5\.3</span>.*?<!-- e53-toc -->\n', re.S)

def set_toc(h, page):
    block = TOC.format(c="#" if page == "e53.html" else "e53.html#", l="#" if page == "e53-legacy.html" else "e53-legacy.html#")
    if OLD_TOC.search(h):
        return OLD_TOC.sub(lambda m: block, h, count=1)
    i = h.find('e52-more">'); j = h.find("</ol></li>", i) + len("</ol></li>\n")
    return h[:j] + block + h[j:]

MOVED = re.compile(r'href="e53\.html#(' + "|".join(re.escape(i) for i in sorted(leg_ids, key=len, reverse=True)) + r')"')
GEN = ("e53.html", "e53-legacy.html")
pages = sorted(p for p in d.glob("*.html") if p.name not in GEN)
for f in pages:
    h = set_toc(f.read_text(), f.name)
    h = MOVED.sub(r'href="e53-legacy.html#\1"', h)  # links into the moved blocks
    if f.name == "e52.html":
        h = re.sub(r"\n*<!-- e53:start.*?<!-- e53:end -->\n*", "\n\n", h, flags=re.S)
        note = ' 매 라운드 과제(시그널 게임)는 <a href="e53.html#e53">5.3</a>에 따로 있습니다.'
        k = h.find('v0~v11 설계 · 스모크 · 루브릭 · 검토 기록은')
        if k > 0 and "e53.html#e53\">5.3</a>에 따로" not in h:
            e = h.find("</p>", k); h = h[:e] + note + h[e:]
    if f.name == "e52-legacy.html":
        h = h.replace('<a href="e52.html">← 5.2 행동 · 현재 (v12)</a><span></span></nav>',
                      '<a href="e52.html">← 5.2 행동 · 현재 (v12)</a><a href="e53.html">5.3 시그널 게임 →</a></nav>')
    if f.name == "maint.html":
        h = h.replace('<nav class="pager" aria-label="페이지 이동"><a href="e53.html">← 5.3 시그널 게임</a>',
                      '<nav class="pager" aria-label="페이지 이동"><a href="e53-legacy.html">← 5.3 지난 설계</a>')
    f.write_text(h)

idx = (d / "index.html").read_text()
base = idx[: idx.index("<main")].replace('href="#', 'href="index.html#')
TAIL = '</main>\n</div>\n\n<script src="site.js"></script>\n</body></html>\n'
nxt = '<a href="maint.html">6 아레나 유지 보수 →</a>' if (d / "maint.html").exists() else "<span></span>"
head = set_toc(base.replace("<title>Squid Game 5 세팅</title>", "<title>Squid Game 5 · 5.3 시그널 게임</title>"), "e53.html")
page = (head + '<main class="main">\n<p class="eyebrow crumb"><a href="index.html">Squid Game 5</a> · 5.3 시그널 게임</p>\n'
        + cur + '\n<nav class="pager" aria-label="페이지 이동"><a href="e52-legacy.html">← 5.2 지난 설계</a>'
        '<a href="e53-legacy.html">5.3 지난 설계 (v12 ~ M6) →</a></nav>\n' + TAIL)
(d / "e53.html").write_text(page)
head = set_toc(base.replace("<title>Squid Game 5 세팅</title>", "<title>Squid Game 5 · 5.3 지난 설계</title>"), "e53-legacy.html")
lpage = (head + '<main class="main">\n<p class="eyebrow crumb"><a href="index.html">Squid Game 5</a> · '
         '<a href="e53.html">5.3 시그널 게임</a> · 지난 설계</p>\n'
         + leg + '\n<nav class="pager" aria-label="페이지 이동"><a href="e53.html">← 5.3 시그널 게임 · 현재 (v15)</a>' + nxt + '</nav>\n' + TAIL)
(d / "e53-legacy.html").write_text(lpage)

# site.js: an old #id link lands on the page that now holds it
js = js0 = (d / "site.js").read_text()
W = {i: "e53.html" for i in ["e53"] + [i for i, _ in CUR_TOC]}
W.update({i: "e53-legacy.html" for i in ["e53-legacy"] + [i for i, _ in LEG_TOC] + ["sg53-fig"]})
for i, pg in W.items():
    pat = re.compile(r'"' + re.escape(i) + r'":"[^"]*"')
    if pat.search(js):
        js = pat.sub(f'"{i}":"{pg}"', js, count=1)
    else:
        anchor = '"e53":"e53.html"' if '"e53":"e53.html"' in js else '"e52-v13-figI":"e52-legacy.html"'
        assert anchor in js, "site.js anchor missing"
        js = js.replace(anchor, anchor + f',"{i}":"{pg}"', 1)
if js != js0:
    (d / "site.js").write_text(js)
print("ok", len(page), len(lpage))
