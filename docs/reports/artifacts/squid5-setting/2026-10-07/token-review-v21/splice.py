"""v21 (10-16): copy the token review section of work.html (built by build.py -> build_semantic_transfers.py ->
build_survival_relation.py -> build_solver_budget.py, all on the v21 runs) into e52.html between the
<!-- e52-v21token:start/end --> markers (if the markers are missing, the block goes right after
<!-- e52-v21cases:end -->). Headings move one level down (h2 -> h3, h3 -> h4) and every id gets a 'v21-' prefix so
the v20 copy of the same section on e52-legacy.html keeps its own ids.
Usage (from this folder): python3 splice.py [--page PATH]   (default: ../e52.html)"""
import argparse
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ap = argparse.ArgumentParser()
ap.add_argument('--page', type=Path, default=HERE.parent / 'e52.html', help='page to splice into (default ../e52.html)')
PAGE = ap.parse_args().page
work = (HERE / 'work.html').read_text(encoding='utf-8')
css = re.search(r'<style>\n(\.tr\{.*?)</style>', work, re.S).group(1)
a = work.index('<section class="tr" aria-labelledby="token-review" id="token-review-section">')
sec = work[a:work.index('</section>', a) + len('</section>')]
# As v20 (10-16 15:45, researcher): a plainer section - no kicker, an ordinary heading, no "현재 판정" box, and 03-B,
# 04 (A-C) and 05 left out; the rest of the review is kept as built.
def cut(text, start, end):  # drop text[start:end] by markers; both must be present
    i = text.index(start)
    return text[:i] + text[text.index(end, i):]
sec = re.sub(r'<p class="tr-kicker">.*?</p>\n', '', sec, count=1)
sec = sec.replace('<h2 id="token-review">토큰을 어떻게 써서,<br>과제를 계속하는가</h2>', '<h2 id="token-review">v21 · 토큰을 어떻게 써서 과제를 계속하는가</h2>')
sec = re.sub(r'<p class="tr-lead">.*?</p>', '<p class="small">우승은 결과다. 이 절은 <b>자원 운용 · 과제 참여 지속 · 실제 이전</b>을 나누어 읽는다.</p>', sec, count=1)
sec = re.sub(r'<div class="tr-verdict"><b>현재 판정:.*?</div>\n', '', sec, count=1, flags=re.S)
sec = re.sub(r'<a href="#token-value">[^<]*</a><a href="#token-changes">[^<]*</a>', '', sec)
sec = cut(sec, '<h4 id="transfer-deficit">', '<h4>모델별 무게중심')
sec = re.sub(r'<tr><td>실제 부족 전체</td>.*?</tr>', '', sec)
sec = cut(sec, '<h3 id="token-value">', '<h3 id="token-changes">')
sec = cut(sec, '<h3 id="token-changes">', '<p class="tr-note">재현:')
ids = set(re.findall(r'id="([^"]+)"', sec))
for i in sorted(ids, key=len, reverse=True):
    sec = sec.replace(f'id="{i}"', f'id="v21-{i}"').replace(f'href="#{i}"', f'href="#v21-{i}"')
sec = sec.replace('aria-labelledby="token-review"', 'aria-labelledby="v21-token-review"')
sec = sec.replace('<h3', '<h4').replace('</h3>', '</h4>').replace('<h2', '<h3').replace('</h2>', '</h3>')
css = css.replace('.tr h3', '.tr h4').replace('.tr h2', '.tr h3')
css = re.sub(r'\.tr h3\{[^}]*\}', '', css)  # the title takes the page's own h3 style
css = re.sub(r'\.tr h4\{[^}]*\}', '.tr h4{margin-top:28px}', css)  # section headings: the page's h4 size
block = ('<!-- e52-v21token:start (generated by token-review-v21/splice.py from token-review-v21/work.html) -->\n'
         '<style>\n' + css + '.tr figure .tr-legend{color:#d6dde3}\n.tr figure,.tr .sb-chart{color:#d6dde3}  /* 10-16: text inside the dark figures (legends, solver-budget titles and numbers) was dark on dark */\n</style>\n' + sec + '\n<!-- e52-v21token:end -->')
h = PAGE.read_text(encoding='utf-8')
if '<!-- e52-v21token:start' in h:
    i, j = h.index('<!-- e52-v21token:start'), h.index('<!-- e52-v21token:end -->') + len('<!-- e52-v21token:end -->')
    h = h[:i] + block + h[j:]
else:
    k = h.index('<!-- e52-v21cases:end -->') + len('<!-- e52-v21cases:end -->')
    h = h[:k] + '\n\n' + block + h[k:]
PAGE.write_text(h, encoding='utf-8')
print('ok', PAGE, len(block), len(ids), 'ids')
