def date_index(ctx, date, exps):
    ddir = os.path.join(ctx.res, date)
    out = [MARK, "", f"# {date} (KST) 실험", ""]
    if os.path.isfile(os.path.join(ddir, "_legacy_outputs_INDEX.md")):
        out += [f"옛 `outputs/{date}/INDEX.md`(런 단위 표, UTC 시각)는 {link('_legacy_outputs_INDEX.md', '_legacy_outputs_INDEX.md')}에 있다. "
                "날짜를 KST 시작일로 다시 매겨서, 그 표의 런 일부는 다른 날짜 폴더로 갔을 수 있다.", ""]
    if not exps:
        out += ["이 날짜를 시작일로 하는 실험은 없다.", ""]
        return "\n".join(out)
    out += ["| 실험 | 한 줄 요약 | runs | analysis | reports | README |", "|---|---|--:|--:|--:|---|"]
    for e in exps:
        meta = ctx.experiments.get(f"{date}/{e}", {})
        n_r, n_a, n_p = counts(os.path.join(ddir, e))
        summ = first_sentence(meta.get("summary_ko", "")) or meta.get("title_ko", "") or "(메타데이터 없음 — README 참고)"
        title = meta.get("title_ko") or e
        out.append(f"| `{e}`<br>{cell(title)} | {cell(summ)} | {n_r} | {n_a} | {n_p} | {link('README', f'{e}/README.md')} |")
    out += ["", "runs 수는 `runs/` 아래 폴더 수(`_`로 시작하는 로그 폴더 제외), reports 수는 `reports/*.html` 수다. "
            "런 폴더 안의 `runs/*/reports/` 페이지는 세지 않았다.", ""]
    return "\n".join(out)


