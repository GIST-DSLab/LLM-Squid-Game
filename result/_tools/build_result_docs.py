# ---------------------------------------------------------------- helpers
def load_json(path, default):
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except (OSError, ValueError):
        return default


def cell(s):
    """Make a string safe for one markdown table cell."""
    s = re.sub(r"\s+", " ", str(s or "")).strip()
    return s.replace("|", "\\|")


def link(text, path):
    return f"[{text}](<{path}>)"


def first_sentence(s, cap=150):
    s = re.sub(r"\s+", " ", s or "").strip()
    m = re.search(r"(?<=다\.)\s|(?<=[.!?])\s(?=[A-Z가-힣`(])", s)
    if m:
        s = s[: m.start()]
    return s if len(s) <= cap else s[: cap - 1].rstrip() + "…"


def html_title(path):
    try:
        with open(path, "rb") as f:
            data = f.read(400_000)
        m = re.search(rb"<title[^>]*>(.*?)</title>", data, re.S | re.I)
        if not m:
            with open(path, "rb") as f:
                m = re.search(rb"<title[^>]*>(.*?)</title>", f.read(), re.S | re.I)
        return html.unescape(m.group(1).decode("utf-8", "replace")).strip() if m else ""
    except OSError:
        return ""


def md_heading_and_desc(path):
    """First '# ' heading, plus a description: first blockquote line, else first plain line."""
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            lines = [l.rstrip("\n") for l in f.readlines()[:80]]
    except OSError:
        return "", ""
    head = next((l.lstrip("#").strip() for l in lines if l.startswith("#")), "")
    quote = next((l.lstrip("> ").strip() for l in lines if l.startswith(">") and l.strip("> ")), "")
    plain = next((l.strip() for l in lines if l.strip() and not l.startswith(("#", ">", "|", "<!--", "-", "```"))
                  and not l.startswith(("Run on", "Stated in"))), "")
    return head, quote or plain


def human_size(n):
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024


def dir_stats(path):
    files, size = 0, 0
    for d, _, fs in os.walk(path):
        for fn in fs:
            files += 1
            try:
                size += os.path.getsize(os.path.join(d, fn))
            except OSError:
                pass
    return files, size


def listdir(path):
    try:
        return sorted(e for e in os.listdir(path) if not e.startswith(".") and e != "Icon\r")
    except OSError:
        return []


# ---------------------------------------------------------------- context
class Ctx:
    def __init__(self, repo, meta):
        self.repo = repo.rstrip("/")
        self.res = os.path.join(self.repo, "result")
        self.experiments = load_json(os.path.join(meta, "experiments.json"), {})
        self.placed = load_json(os.path.join(meta, "placed_reports.json"), [])
        inv = load_json(os.path.join(meta, "inv_html.json"), {})
        self.inv = {f["path"]: f for f in inv.get("files", [])} if isinstance(inv, dict) else {}
        self.split = {}
        for mf in sorted(glob.glob(os.path.join(meta, "split", "manifest_*.json"))):
            for p in load_json(mf, {}).get("pages", []):
                self.split[p["file"]] = p
        self.moves = []
        try:
            with open(os.path.join(self.res, "_movelog.tsv"), encoding="utf-8") as f:
                for line in f:
                    parts = line.rstrip("\n").split("\t")
                    if len(parts) == 3:
                        self.moves.append(tuple(parts))
        except OSError:
            pass
        self.written, self.skipped = [], []

    def short(self, p):
        if p.startswith(self.repo + "/"):
            return p[len(self.repo) + 1:]
        if p.startswith(HOME + "/"):
            return "~/" + p[len(HOME) + 1:]
        return p

    def write(self, path, text, dry):
        if os.path.exists(path):
            with open(path, encoding="utf-8", errors="replace") as f:
                if MARK not in f.read():
                    self.skipped.append(path)
                    return
        if not dry:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
        self.written.append(path)


METHOD_KO = {"git_mv": "git mv", "mv": "mv (미추적)", "copy": "복사 (원본 유지)"}


