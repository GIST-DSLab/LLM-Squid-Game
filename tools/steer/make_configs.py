"""Write the steering run configs (configs/squid5/steer/) from the as-run v33 arena config.

    python tools/steer/make_configs.py            # (re)write every file
    python tools/steer/make_configs.py --check    # exit 1 if a file differs from what would be written

Every arena config copies ``game`` and ``cells`` of e52v33_ollama_gptoss4.yaml unchanged (seeds 4101-4105) and differs
only in the model line: the condition name sent to the steering server (tools/steer/server.py). Every refill config asks
the 5.1 v11 pair (self.D, other.D) of squid5/prompts/en/refill.yaml under the same condition, the manipulation check.
The files sit in a subfolder so the v33 / refill config counts that tests/ pin stay as they are.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "configs/squid5/e52v33_ollama_gptoss4.yaml"
OUT = REPO / "configs/squid5/steer"
ALIAS = "qwen3-8b"
CONDITIONS = ("", "random@0.5", "random@1.0", "survival@0.5", "survival@1.0", "sharing@0.5", "sharing@1.0",
              "alone@0.5", "alone@1.0")
SERVER = "http://127.0.0.1:8700/v1"


def tag(cond: str) -> str:
    return cond.replace("@", "").replace(".", "").replace("-", "m") if cond else "base"


def model(cond: str) -> dict:
    # think high -> reasoning_effort -> thinking on (the server ignores the level); temperature 0.6 = Qwen3's thinking default
    return {"kind": "openai", "model": ALIAS + (f"+{cond}" if cond else ""), "base_url": SERVER,
            "api_key_env": "STEER_API_KEY", "think": "high", "temperature": 0.6, "timeout": 7200, "retries": 2}


def configs() -> dict[str, tuple[str, dict]]:
    src = yaml.safe_load(SRC.read_text())
    out = {}
    for c in CONDITIONS:
        name = model(c)["model"]
        out[f"e52v33_steer_{tag(c)}.yaml"] = (
            f"# Qwen persona steering, arena: v33 as e52v33_ollama_gptoss4.yaml (game and cells unchanged) on {name}.\n"
            "# Generated by tools/steer/make_configs.py; plan docs/history/plans/2026-10-28-qwen-persona-steering.md.\n"
            "# One GPU server (tools/steer/server.py) answers every call, so one game at a time.\n",
            {"name": f"squid5_e52v33_steer_{tag(c)}", "mode": "game", "reps": 5, "seed0": 4101, "workers": 1,
             "out_root": "~/squid5-runs/e52_v33_steer", "model": model(c), "game": src["game"], "cells": src["cells"]})
        out[f"refill_steer_{tag(c)}.yaml"] = (
            f"# Qwen persona steering, manipulation check: 5.1 v11 refill pair (self.D, other.D) on {name}.\n"
            "# Generated by tools/steer/make_configs.py. 20 answers per counter and cell, as the refill_*.yaml runs.\n",
            {"name": f"squid5_refill_steer_{tag(c)}", "mode": "refill", "model": model(c), "reps": 20, "workers": 4,
             "out_root": "~/squid5-runs/e5x_steer",
             "cells": [{"cell_id": "D", "currency": "tokens", "arm": "self.D"},
                       {"cell_id": "other_D", "currency": "tokens", "arm": "other.D"}],
             "refill": {"pairs": [["D", "other_D"]], "compare": []}})
    return out


def render(header: str, cfg: dict) -> str:
    return header + yaml.safe_dump(cfg, sort_keys=False, default_flow_style=None, width=120)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    stale = []
    for fname, (header, cfg) in configs().items():
        path, text = OUT / fname, render(header, cfg)
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(fname)
            continue
        OUT.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    if stale:
        print("stale: " + ", ".join(stale), file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
