"""Write squid5 5.2 v35 configs whose four seats are Qwen3-8B behind persona_arena.server.

The game section is copied from the engine's v35 config, so only the seats differ between arms (same seeds = paired).

    uv run python make_configs.py                       # one homogeneous table per persona (4 x same persona)
    uv run python make_configs.py --mixed community_spirit scheming_tyrant   # 2 + 2 table
"""
import argparse
from pathlib import Path

import yaml

from persona_arena.library import load_personas

ENGINE = Path.home() / "wt" / "squid5-e52"
BASE = ENGINE / "configs" / "squid5" / "e52v35_ollama_gptoss4.yaml"
AGENTS = ["agent-6", "agent-11", "agent-17", "agent-23"]  # squid5.core.rules.TEAM_AGENTS
OUT = Path(__file__).resolve().parent / "configs"


def seat(pid: str, port: int, k: float) -> dict:
    model = "qwen3-8b" if pid == "baseline" else f"qwen3-8b@{pid}" + (f"*{k:g}" if k != 1 else "")
    # think on for SOLVE, off for TALK (tokctl practice for open models); one local model -> long timeouts
    return {"kind": "openai", "model": model, "base_url": f"http://127.0.0.1:{port}/v1", "api_key_env": "QWEN_STEER_KEY",
            "think": "high", "think_talk": "none", "temperature": 0.6, "timeout": 7200, "retries": 2}


def write(name: str, seats: dict, reps: int, seed0: int, out_root: str):
    base = yaml.safe_load(BASE.read_text())
    cfg = {"name": f"squid5_e52v35_qwen8b_{name}", "mode": "game", "reps": reps, "seed0": seed0,
           "workers": 1,  # one model on one device; the server serialises calls anyway
           "out_root": out_root, "model": dict(seats[AGENTS[0]]),
           "game": {**base["game"], "seats": seats}, "cells": base["cells"]}
    OUT.mkdir(exist_ok=True)
    path = OUT / f"e52v35_qwen8b_{name}.yaml"
    head = (f"# generated by make_configs.py from {BASE.name} (game section unchanged); seats = Qwen3-8B via\n"
            f"# persona_arena.server. Run from {ENGINE}: QWEN_STEER_KEY=local python -m squid5 run {path}\n")
    path.write_text(head + yaml.safe_dump(cfg, sort_keys=False, width=120))
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=8610)
    ap.add_argument("--reps", type=int, default=5)
    ap.add_argument("--seed0", type=int, default=4101)
    ap.add_argument("--k", type=float, default=1.0, help="dose multiplier on every persona's alpha")
    ap.add_argument("--out-root", default="~/squid5-runs/e52_v35_qwen8b")
    ap.add_argument("--mixed", nargs=2, metavar=("A", "B"), help="2 + 2 table instead of homogeneous ones")
    a = ap.parse_args()
    personas = load_personas()
    if a.mixed:
        for pid in a.mixed:
            assert pid in personas, pid
        s = {ag: seat(a.mixed[i % 2], a.port, a.k) for i, ag in enumerate(AGENTS)}
        print(write(f"mix_{a.mixed[0]}_{a.mixed[1]}", s, a.reps, a.seed0, a.out_root))
        return
    for pid in personas:
        print(write(pid, {ag: seat(pid, a.port, a.k) for ag in AGENTS}, a.reps, a.seed0, a.out_root))


if __name__ == "__main__":
    main()
